CREATE OR REPLACE FUNCTION public.refund_allows(_key text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT auth.uid() IS NOT NULL AND (
    public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'management') OR
    CASE WHEN _key = 'refunds.view'
      THEN COALESCE(public.perm_key_level(auth.uid(), _key), 'view') <> 'none'
      ELSE COALESCE(public.perm_key_level(auth.uid(), 'refunds.view'), 'view') <> 'none'
           AND COALESCE(public.perm_key_level(auth.uid(), _key), 'none') IN ('add','edit','full')
    END)
$$;

CREATE TABLE public.refunds (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  sr_no bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  name text NOT NULL,
  policy_no text NOT NULL,
  agent_name text,
  premium numeric NOT NULL DEFAULT 0,
  do_name text,
  do_user_id uuid,
  refunded numeric NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'not_paid' CHECK (status IN ('paid','not_paid')),
  refund_process_date date,
  import_batch uuid,
  created_by uuid DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX refunds_policy_unique ON public.refunds (lower(btrim(policy_no)));
CREATE INDEX refunds_do_user_idx ON public.refunds (do_user_id);

CREATE TABLE public.refund_remarks (
  refund_id uuid PRIMARY KEY REFERENCES public.refunds(id) ON DELETE CASCADE,
  remarks text,
  updated_by uuid DEFAULT auth.uid(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.refunds TO authenticated;
GRANT ALL ON public.refunds TO service_role;
GRANT SELECT, INSERT, UPDATE ON public.refund_remarks TO authenticated;
GRANT ALL ON public.refund_remarks TO service_role;
ALTER TABLE public.refunds ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.refund_remarks ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.can_see_refund(_do uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.refund_allows('refunds.view') AND (
    public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'management')
    OR _do = auth.uid() OR public.is_team_lead_of(_do))
$$;

CREATE POLICY refunds_select ON public.refunds FOR SELECT TO authenticated USING (public.can_see_refund(do_user_id));
CREATE POLICY refunds_insert ON public.refunds FOR INSERT TO authenticated
  WITH CHECK (public.refund_allows('refunds.add') OR public.refund_allows('refunds.import'));
CREATE POLICY refunds_update ON public.refunds FOR UPDATE TO authenticated
  USING (public.can_see_refund(do_user_id) AND (public.refund_allows('refunds.edit') OR public.refund_allows('refunds.status')))
  WITH CHECK (public.can_see_refund(do_user_id) OR public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'management') OR public.refund_allows('refunds.edit'));
CREATE POLICY refunds_delete ON public.refunds FOR DELETE TO authenticated
  USING (public.has_role(auth.uid(),'admin') OR public.has_role(auth.uid(),'management'));

CREATE POLICY refund_remarks_select ON public.refund_remarks FOR SELECT TO authenticated
  USING (public.refund_allows('refunds.remarks') AND EXISTS (SELECT 1 FROM public.refunds r WHERE r.id = refund_id AND public.can_see_refund(r.do_user_id)));
CREATE POLICY refund_remarks_write ON public.refund_remarks FOR INSERT TO authenticated
  WITH CHECK (public.refund_allows('refunds.edit') AND EXISTS (SELECT 1 FROM public.refunds r WHERE r.id = refund_id AND public.can_see_refund(r.do_user_id)));
CREATE POLICY refund_remarks_update ON public.refund_remarks FOR UPDATE TO authenticated
  USING (public.refund_allows('refunds.edit') AND EXISTS (SELECT 1 FROM public.refunds r WHERE r.id = refund_id AND public.can_see_refund(r.do_user_id)));

CREATE OR REPLACE FUNCTION public.tg_refunds_before()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE _id uuid; _n int;
BEGIN
  IF TG_OP = 'INSERT' OR NEW.do_name IS DISTINCT FROM OLD.do_name THEN
    SELECT count(*), min(id::text)::uuid INTO _n, _id FROM public.profiles
      WHERE NEW.do_name IS NOT NULL AND lower(btrim(full_name)) = lower(btrim(NEW.do_name));
    NEW.do_user_id := CASE WHEN _n = 1 THEN _id ELSE NULL END;
  END IF;
  IF TG_OP = 'INSERT' THEN
    NEW.status := 'not_paid';
    NEW.created_by := auth.uid();
  ELSE
    IF auth.uid() IS NOT NULL AND NOT public.refund_allows('refunds.edit') AND (
      NEW.name, NEW.policy_no, NEW.agent_name, NEW.premium, NEW.do_name, NEW.refunded, NEW.refund_process_date)
      IS DISTINCT FROM (OLD.name, OLD.policy_no, OLD.agent_name, OLD.premium, OLD.do_name, OLD.refunded, OLD.refund_process_date) THEN
      RAISE EXCEPTION 'You do not have permission to edit refund details';
    END IF;
    IF auth.uid() IS NOT NULL AND NEW.status IS DISTINCT FROM OLD.status AND NOT public.refund_allows('refunds.status') THEN
      RAISE EXCEPTION 'You do not have permission to update refund status';
    END IF;
    NEW.sr_no := OLD.sr_no; NEW.created_by := OLD.created_by; NEW.created_at := OLD.created_at;
    NEW.updated_by := auth.uid(); NEW.updated_at := now();
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER refunds_before BEFORE INSERT OR UPDATE ON public.refunds FOR EACH ROW EXECUTE FUNCTION public.tg_refunds_before();

CREATE OR REPLACE FUNCTION public.tg_refund_remarks_before()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_by := auth.uid(); NEW.updated_at := now();
  UPDATE public.refunds SET updated_at = now() WHERE id = NEW.refund_id AND false;
  RETURN NEW; END $$;
CREATE TRIGGER refund_remarks_before BEFORE INSERT OR UPDATE ON public.refund_remarks FOR EACH ROW EXECUTE FUNCTION public.tg_refund_remarks_before();